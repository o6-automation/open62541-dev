"""Extract a subset of the nodes of a NodeSet2 XML file (e.g. the full namespace
zero from deps/ua-nodeset) for the minimal nodesets in tools/schema. The
selected nodes are copied verbatim. References to nodes that are neither
selected nor defined in one of the base nodesets are dropped (and listed on
stderr), so that the subset can be loaded on top of the base nodesets by the
nodeset compiler."""

import argparse
import re
import sys
import textwrap

NODE_RE = re.compile(r'^  <(UA\w+) NodeId="([^"]+)".*?^  </\1>\n', re.M | re.S)
ALIAS_RE = re.compile(r'<Alias Alias="([^"]+)">([^<]+)</Alias>')
REF_RE = re.compile(r'^\s*<Reference ReferenceType="([^"]+)"[^>]*>([^<]+)</Reference>\n', re.M)

def parse(path):
    with open(path, encoding='utf-8') as f:
        text = f.read()
    nodes = {m.group(2): m for m in NODE_RE.finditer(text)}
    aliases = dict(ALIAS_RE.findall(text))
    return text, nodes, aliases

def numeric(nodeid):
    return nodeid[2:] if nodeid.startswith('i=') else nodeid

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('-b', dest='base', action='append', default=[],
                    help='nodeset the subset is loaded on top of (repeatable)')
parser.add_argument('-d', dest='description', default='',
                    help='description added to the header comment')
parser.add_argument('source', help='NodeSet2 XML file to extract from')
parser.add_argument('outfile', help='output NodeSet2 XML file')
parser.add_argument('nodeids', nargs='+', help='numeric ns=0 NodeIds to extract')
args = parser.parse_args()

text, nodes, aliases = parse(args.source)
available = set()
for base in args.base:
    _, bnodes, baliases = parse(base)
    available |= set(bnodes)
    aliases = {**baliases, **aliases}

selected = ['i=' + numeric(n) for n in args.nodeids]
for n in selected:
    if n not in nodes:
        sys.exit('NodeId %s not found in %s' % (n, args.source))
available |= set(selected)

def resolve(name):
    return aliases.get(name, name)

usedAliases = set()
out = []
# Keep the order of the source file for a stable output
for nodeid, m in nodes.items():
    if nodeid not in selected:
        continue
    node = m.group(0)
    def filterRef(r):
        if resolve(r.group(1)) not in available:
            sys.exit('%s: unknown ReferenceType %s' % (nodeid, r.group(1)))
        if resolve(r.group(2)) not in available:
            print('%s: dropped %s reference to %s' % (nodeid, r.group(1), r.group(2)),
                  file=sys.stderr)
            return ''
        usedAliases.add(r.group(1))
        return r.group(0)
    node = REF_RE.sub(filterRef, node)
    for attr in ('ParentNodeId', 'DataType', 'MethodDeclarationId'):
        a = re.search(r'^  <UA\w+ [^>]*\b%s="([^"]+)"' % attr, node)
        if not a:
            continue
        if resolve(a.group(1)) not in available:
            sys.exit('%s: %s %s is not available' % (nodeid, attr, a.group(1)))
        usedAliases.add(a.group(1))
    # Only warn, the DataType of a Definition field may be known otherwise
    for f in re.findall(r'<Field [^>]*\bDataType="([^"]+)"', node):
        if resolve(f) not in available:
            print('%s: DataType %s of a Definition field is neither selected nor '
                  'in a base nodeset' % (nodeid, f), file=sys.stderr)
    out.append(node)

license = ''.join(l.rstrip() + '\n' for l in re.search(r'<!--.*?-->\n', text, re.S).group(0).splitlines())
header = re.search(r'<UANodeSet [^>]*>\n\s*<Models>.*?</Models>\n', text, re.S).group(0)
command = (['python3 tools/generate_nodeset_subset.py'] +
           ['  -b ' + b for b in args.base] +
           (['  -d "%s"' % args.description] if args.description else []) +
           ['  ' + args.source, '  ' + args.outfile] +
           textwrap.wrap(' '.join(numeric(n) for n in selected), 66,
                         initial_indent='  ', subsequent_indent='  '))
info = ['Generated by tools/generate_nodeset_subset.py, do not edit by hand.']
if args.description:
    info += [args.description]
info += ['', 'The nodes are copied verbatim from the source nodeset. References to',
         'nodes outside of the subset and the base nodesets are removed.',
         'Regenerate with:', '']
info += ['  ' + l + ' \\' for l in command[:-1]] + ['  ' + command[-1]]
comment = '<!--\n' + ''.join((' * ' + l).rstrip() + '\n' for l in info) + '-->\n'
if '--' in comment[4:-4]:
    sys.exit('The header comment must not contain "--"')

usedAliases = sorted((a for a in usedAliases if a in aliases),
                     key=lambda a: list(aliases).index(a))
with open(args.outfile, 'w', encoding='utf-8') as f:
    f.write('<?xml version="1.0" encoding="utf-8" ?>\n')
    f.write(license)
    f.write(comment + '\n')
    f.write(header)
    if usedAliases:
        f.write('  <Aliases>\n')
        for a in usedAliases:
            f.write('    <Alias Alias="%s">%s</Alias>\n' % (a, aliases[a]))
        f.write('  </Aliases>\n')
    f.write(''.join(out))
    f.write('</UANodeSet>\n')
